using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Cascade.Generators;

/// <summary>
/// Makes a component's constructor arguments reach it when its parent re-renders.
///
/// <para>
/// A parent's <c>Render()</c> builds a new instance of each child component, but the mounted child
/// (and its state) lives on and the new one is discarded. Without this, the child kept the
/// arguments its first instance was built with: a <c>new StationTile(station)</c> in a list
/// showed its first station forever. Its inputs are its readonly fields assigned from a
/// constructor parameter (or get-only auto-properties set the same way); state is everything else.
/// </para>
///
/// <para>
/// User components are not <c>partial</c>, so nothing can be added to them. For each one this
/// emits <c>[UnsafeAccessor]</c> field accessors (AOT- and trim-safe) and an adopter that copies
/// the inputs from the new instance onto the live one, registered with <c>ComponentInputs</c> by a
/// module initializer. The reconciler calls it, then re-renders the child as it always did.
/// Components the generated code cannot name (private nested, generic) are skipped.
/// </para>
/// </summary>
internal static class InputAdoptionGenerator
{
    private const string ComponentFullName = "Cascade.UI.Component";

    public static void Register(IncrementalGeneratorInitializationContext context)
    {
        var adopters = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: SignalFieldRewriter.IsComponentCandidate,
                transform: Analyze)
            .Where(adopter => adopter is not null)
            .Collect();

        context.RegisterSourceOutput(adopters, static (spc, all) =>
        {
            var unique = all
                .Where(a => a is not null)
                .Select(a => a!.Value)
                .GroupBy(a => a.TypeName, StringComparer.Ordinal)
                .Select(g => g.First())
                .OrderBy(a => a.TypeName, StringComparer.Ordinal)
                .ToList();
            if (unique.Count == 0)
            {
                return;
            }

            var source = new StringBuilder();
            source.AppendLine("// <auto-generated/>");
            source.AppendLine("#nullable disable");
            source.AppendLine("namespace Cascade.Generated");
            source.AppendLine("{");
            int index = 0;
            foreach (var adopter in unique)
            {
                source.Append(adopter.ClassCode.Replace("__INDEX__", index.ToString(System.Globalization.CultureInfo.InvariantCulture)));
                index++;
            }
            source.AppendLine("    internal static class CascadeComponentInputsRegistration");
            source.AppendLine("    {");
            source.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            source.AppendLine("        internal static void Register()");
            source.AppendLine("        {");
            index = 0;
            foreach (var adopter in unique)
            {
                source.Append("            global::Cascade.UI.ComponentInputs.Register(typeof(").Append(adopter.TypeName)
                    .Append("), CascadeComponentInputs").Append(index.ToString(System.Globalization.CultureInfo.InvariantCulture)).AppendLine(".Adopt);");
                index++;
            }
            source.AppendLine("        }");
            source.AppendLine("    }");
            source.AppendLine("}");
            spc.AddSource("CascadeComponentInputs.g.cs", source.ToString());
        });
    }

    private static (string TypeName, string ClassCode)? Analyze(GeneratorSyntaxContext context, CancellationToken ct)
    {
        var classDecl = (ClassDeclarationSyntax)context.Node;
        var model = context.SemanticModel;
        if (model.GetDeclaredSymbol(classDecl, ct) is not INamedTypeSymbol type
            || type.IsAbstract
            || !InheritsFromComponent(type)
            || !IsNameable(type))
        {
            return null;
        }

        // Only the first partial declaration analyses, over every declaration of the type.
        if (type.DeclaringSyntaxReferences.Length > 1
            && type.DeclaringSyntaxReferences[0].GetSyntax(ct) != classDecl)
        {
            return null;
        }

        var inputs = new List<(string Name, string Type, string DeclaringType)>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        for (var current = type; current is not null && current.ToDisplayString() != ComponentFullName; current = current.BaseType)
        {
            if (!IsNameable(current) || current.DeclaringSyntaxReferences.Length == 0)
            {
                continue;
            }
            foreach (var reference in current.DeclaringSyntaxReferences)
            {
                if (reference.GetSyntax(ct) is not ClassDeclarationSyntax declaration)
                {
                    continue;
                }
                var declarationModel = model.Compilation.GetSemanticModel(declaration.SyntaxTree);
                CollectInputs(declaration, declarationModel, current, inputs, seen, ct);
            }
        }
        if (inputs.Count == 0)
        {
            return null;
        }

        string typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var code = new StringBuilder();
        code.AppendLine("    file static class CascadeComponentInputs__INDEX__");
        code.AppendLine("    {");
        for (int i = 0; i < inputs.Count; i++)
        {
            var input = inputs[i];
            code.Append("        [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Field, Name = \"")
                .Append(input.Name).AppendLine("\")]");
            code.Append("        private static extern ref ").Append(input.Type).Append(" Input").Append(i)
                .Append('(').Append(input.DeclaringType).AppendLine(" component);");
        }
        code.AppendLine();
        code.AppendLine("        internal static void Adopt(global::Cascade.UI.Component live, global::Cascade.UI.Component newer)");
        code.AppendLine("        {");
        code.Append("            var to = (").Append(typeName).AppendLine(")live;");
        code.Append("            var from = (").Append(typeName).AppendLine(")newer;");
        for (int i = 0; i < inputs.Count; i++)
        {
            code.Append("            Input").Append(i).Append("(to) = Input").Append(i).AppendLine("(from);");
        }
        code.AppendLine("        }");
        code.AppendLine("    }");
        code.AppendLine();
        return (typeName, code.ToString());
    }

    /// <summary>
    /// Readonly instance fields (and get-only auto-properties) of <paramref name="owner"/> that a
    /// constructor assigns from an expression using one of its parameters.
    /// </summary>
    private static void CollectInputs(
        ClassDeclarationSyntax declaration,
        SemanticModel model,
        INamedTypeSymbol owner,
        List<(string Name, string Type, string DeclaringType)> inputs,
        HashSet<string> seen,
        CancellationToken ct)
    {
        string declaringType = owner.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        foreach (var constructor in declaration.Members.OfType<ConstructorDeclarationSyntax>())
        {
            if (constructor.Modifiers.Any(SyntaxKind.StaticKeyword))
            {
                continue;
            }
            SyntaxNode? body = (SyntaxNode?)constructor.Body ?? constructor.ExpressionBody;
            if (body is null)
            {
                continue;
            }
            var parameters = new HashSet<IParameterSymbol>(
                constructor.ParameterList.Parameters
                    .Select(p => model.GetDeclaredSymbol(p, ct))
                    .Where(p => p is not null)!,
                SymbolEqualityComparer.Default);
            if (parameters.Count == 0)
            {
                continue;
            }

            foreach (var assignment in body.DescendantNodesAndSelf().OfType<AssignmentExpressionSyntax>())
            {
                ct.ThrowIfCancellationRequested();
                if (!assignment.IsKind(SyntaxKind.SimpleAssignmentExpression)
                    || !UsesParameter(assignment.Right, model, parameters, ct))
                {
                    continue;
                }

                var target = model.GetSymbolInfo(assignment.Left, ct).Symbol;
                (string Name, ITypeSymbol Type)? input = target switch
                {
                    IFieldSymbol { IsReadOnly: true, IsStatic: false, IsImplicitlyDeclared: false, RefKind: RefKind.None } field
                        when SymbolEqualityComparer.Default.Equals(field.ContainingType, owner) => (field.Name, field.Type),
                    IPropertySymbol { IsReadOnly: true, IsStatic: false } property
                        when SymbolEqualityComparer.Default.Equals(property.ContainingType, owner) && IsAutoProperty(property, ct)
                        => ($"<{property.Name}>k__BackingField", property.Type),
                    _ => null,
                };
                if (input is not { } found || found.Type.IsRefLikeType || !IsNameable(found.Type) || !seen.Add(declaringType + "." + found.Name))
                {
                    continue;
                }
                inputs.Add((found.Name, found.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), declaringType));
            }
        }
    }

    private static bool UsesParameter(ExpressionSyntax expression, SemanticModel model, HashSet<IParameterSymbol> parameters, CancellationToken ct)
    {
        foreach (var identifier in expression.DescendantNodesAndSelf().OfType<IdentifierNameSyntax>())
        {
            if (model.GetSymbolInfo(identifier, ct).Symbol is IParameterSymbol parameter && parameters.Contains(parameter))
            {
                return true;
            }
        }
        return false;
    }

    private static bool IsAutoProperty(IPropertySymbol property, CancellationToken ct)
    {
        foreach (var reference in property.DeclaringSyntaxReferences)
        {
            if (reference.GetSyntax(ct) is PropertyDeclarationSyntax { AccessorList: { } accessors, ExpressionBody: null }
                && accessors.Accessors.All(a => a.Body is null && a.ExpressionBody is null))
            {
                return true;
            }
        }
        return false;
    }

    private static bool InheritsFromComponent(INamedTypeSymbol type)
    {
        for (var current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (current.ToDisplayString() == ComponentFullName)
            {
                return true;
            }
        }
        return false;
    }

    /// <summary>
    /// Whether generated code elsewhere in the assembly can name the type: no private or protected
    /// nesting, no type parameters, and the same for its type arguments and element types.
    /// </summary>
    private static bool IsNameable(ITypeSymbol type)
    {
        switch (type)
        {
            case IArrayTypeSymbol array:
                return IsNameable(array.ElementType);
            case ITypeParameterSymbol:
            case IPointerTypeSymbol:
            case IFunctionPointerTypeSymbol:
                return false;
            case INamedTypeSymbol named:
                for (INamedTypeSymbol? current = named; current is not null; current = current.ContainingType)
                {
                    if (current.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal)
                    {
                        return false;
                    }
                    if (current.IsAnonymousType || current.IsFileLocal)
                    {
                        return false;
                    }
                }
                if (named is { IsGenericType: true, IsUnboundGenericType: false }
                    && named.TypeArguments.Any(argument => !IsNameable(argument)))
                {
                    return false;
                }
                return true;
            default:
                return true;
        }
    }

    private static bool IsNameable(INamedTypeSymbol type)
        => IsNameable((ITypeSymbol)type) && type.TypeParameters.Length == 0
            && (type.ContainingType is null || IsNameable(type.ContainingType));
}
