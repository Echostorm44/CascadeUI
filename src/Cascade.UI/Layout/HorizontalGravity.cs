namespace Cascade.UI;

/// <summary>
/// Horizontal gravity for positioning a node within a container.
/// </summary>
public enum HorizontalGravity
{
    /// <summary>Aligned to the left edge.</summary>
    Left,

    /// <summary>Horizontally centered.</summary>
    Center,

    /// <summary>Aligned to the right edge.</summary>
    Right,

    /// <summary>Horizontally centered within the left third of the container.</summary>
    LeftThird,

    /// <summary>Horizontally centered within the right third of the container.</summary>
    RightThird,
}
