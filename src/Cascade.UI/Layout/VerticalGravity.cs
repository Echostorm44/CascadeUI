namespace Cascade.UI;

/// <summary>
/// Vertical gravity for positioning a node within a container.
/// </summary>
public enum VerticalGravity
{
    /// <summary>Aligned to the top edge.</summary>
    Top,

    /// <summary>Vertically centered.</summary>
    Center,

    /// <summary>Aligned to the bottom edge.</summary>
    Bottom,

    /// <summary>Vertically centered within the top third of the container.</summary>
    TopThird,

    /// <summary>Vertically centered within the bottom third of the container.</summary>
    BottomThird,
}
