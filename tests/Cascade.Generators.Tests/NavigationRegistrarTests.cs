    // ── Basic route registration ──────────────────────────────────────

    [TUnit.Core.Test]
    public async Task SingleRoute_GeneratesRegistration()
    {
        string source = StubTypes + @"
namespace TestApp
{
    [Cascade.UI.Route(""/home"")]
    public class HomePage : Cascade.UI.Component
    {
        protected override Cascade.UI.Node Render() => Cascade.UI.Node.Empty;
    }
}
";
        var result = RunGenerator(source);
        var generated = GetGeneratedSource(result, "RouteRegistration.g.cs");

        await TUnit.Assertions.Assert.That(generated).IsNotNull();
        await TUnit.Assertions.Assert.That(Has(generated, "RouteRegistration")).IsTrue();
        await TUnit.Assertions.Assert.That(Has(generated, "/home")).IsTrue();
        await TUnit.Assertions.Assert.That(Has(generated, "TestApp.HomePage")).IsTrue();
    }

